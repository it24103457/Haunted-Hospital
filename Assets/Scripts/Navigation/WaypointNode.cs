using System.Collections.Generic;
using UnityEngine;
using UnityEngine.AI;

public enum WaypointType
{
    Normal,
    Door,       // node inside a doorway; the nodes in front of and behind it are Normal
    Barricade   // node inside a barricaded opening
}

/*
 * One point of the waypoint graph shared by the Thief and the Hunter.
 * Holds facts only: position, neighbours, and what sits at this point.
 * Costs, A* and agent memory (such as known blocked barricades) live in each agent.
 * Door and barricade references are resolved at runtime, so the graph prefab works in any scene.
 */
public class WaypointNode : MonoBehaviour
{
    [SerializeField] private WaypointType type = WaypointType.Normal;

    [Tooltip("Generated by WaypointGraph's Rebuild Edges.")]
    [SerializeField] private List<WaypointNode> neighbours = new List<WaypointNode>();

    [Tooltip("Search radius used on Awake to find the door or barricade this node belongs to.")]
    [SerializeField] private float detectRadius = 1f;

    private NavMeshObstacle barricadeObstacle;

    public WaypointType Type => type;
    public IReadOnlyList<WaypointNode> Neighbours => neighbours;
    public Vector3 Position => transform.position;

    // The door at this node. Null on non-Door nodes.
    public Door Door { get; private set; }

    // The barricade at this node. Null on non-Barricade nodes.
    public GameObject Barricade { get; private set; }

    /*
     * Shared barricade rule for all agents: intact while it exists, is active and still blocks the NavMesh.
     * Destroyed, deactivated or a disabled obstacle all count as down.
     */
    public bool IsBarricadeIntact =>
        Barricade != null && Barricade.activeInHierarchy &&
        barricadeObstacle != null && barricadeObstacle.enabled;

    private void Awake()
    {
        if (type == WaypointType.Normal) return;

        FindLinkedObject();

        if (Door == null && Barricade == null)
            Debug.LogWarning($"WaypointNode '{name}' is a {type} node but found no {type} within {detectRadius} m.", this);
    }

    // Picks the closest matching door or barricade collider within detectRadius.
    private void FindLinkedObject()
    {
        Collider[] hits = Physics.OverlapSphere(Position, detectRadius, ~0, QueryTriggerInteraction.Collide);
        float best = float.MaxValue;

        foreach (Collider c in hits)
        {
            float distance = (c.bounds.ClosestPoint(Position) - Position).sqrMagnitude;
            if (distance >= best) continue;

            Door door = c.GetComponentInParent<Door>();

            if (type == WaypointType.Door && door != null)
            {
                Door = door;
                best = distance;
            }
            else if (type == WaypointType.Barricade && door == null)
            {
                // Doors also carry a NavMeshObstacle, so objects with a Door are excluded here.
                NavMeshObstacle obstacle = c.GetComponentInParent<NavMeshObstacle>();
                if (obstacle == null) continue;

                Barricade = obstacle.gameObject;
                barricadeObstacle = obstacle;
                best = distance;
            }
        }
    }

#if UNITY_EDITOR
    // Edge editing used by WaypointGraph's Rebuild Edges.
    public void EditorClearNeighbours() => neighbours.Clear();

    public void EditorAddNeighbour(WaypointNode node)
    {
        if (node != null && node != this && !neighbours.Contains(node))
            neighbours.Add(node);
    }
#endif

    // Cyan = Normal, yellow = Door, red = Barricade, white lines = edges.
    private void OnDrawGizmos()
    {
        switch (type)
        {
            case WaypointType.Door: Gizmos.color = Color.yellow; break;
            case WaypointType.Barricade: Gizmos.color = Color.red; break;
            default: Gizmos.color = Color.cyan; break;
        }
        Gizmos.DrawSphere(Position, 0.2f);

        Gizmos.color = Color.white;
        foreach (WaypointNode n in neighbours)
            if (n != null) Gizmos.DrawLine(Position, n.Position);
    }

    // Selection ring, plus the detect radius on Door and Barricade nodes.
    private void OnDrawGizmosSelected()
    {
        Gizmos.color = Color.green;
        Gizmos.DrawWireSphere(Position, 0.35f);
        if (type != WaypointType.Normal) Gizmos.DrawWireSphere(Position, detectRadius);
    }
}